import genToken from "../config/token.js";
import User from "../models/user.model.js";
import bcrypt from "bcryptjs";

export const signUp = async (req, res) => {
    try {
        const {name, email, password} = req.body;

        const existEmail = await User.findOne({email}); // findOne is used to find the email in db

        if(existEmail) {
            return res.status(400).json({ message: "Email already exists" });
        }

        if(password.length < 6) {
            return res.status(400).json({ message: "Password must be at least 6 characters long" });
        }

        const hashedPassword = await bcrypt.hash(password, 10); // hash is a function in bcryptjs which hash the password

        const user = await User.create({
            name,
            email,
            password: hashedPassword
        });

        /* user create ho chuka hai ab hum token generate karenge (with the help of userId) , aur ye token cookies ke andar
           store ho jayega , to jab hum doobara login karenge to hum login hi milenge */
        // config folder ke andar ye hum karenge -> config/token.js
        
        const token = await genToken(user._id); // user._id is the unique id of the user which is generated by mongodb

        // cookie is a object with has many things
        const isProduction = process.env.NODE_ENV === "production";
        res.cookie("token", token, { // name of cookie is : token
            httpOnly: true,
            maxAge: 10 * 24 * 60 * 60 * 1000, // 10 days (milliseconds)
            sameSite: isProduction ? "None" : "Lax",
            secure: isProduction
        });

        return res.status(201).json(user);

    } catch(error) {
        console.error("Error occurred during signup:", error);
        return res.status(500).json({ message: "Internal server error" });
    }
};

export const Login = async (req, res) => {
    try {
        const {email, password} = req.body;

        const user = await User.findOne({email}); // findOne is used to find the email in db

        // check wheather user(email) exits in db or not
        if(!user) {
            return res.status(400).json({ message: "Email doesn't exists" });
        }

        // match the password 
        const isMatch = await bcrypt.compare(password, user.password); // compare is a function in bcryptjs which compare the password
        // hashedPassword(user.password) user ke andar hoga 

        if(!isMatch) {
            return res.status(400).json({ message: "Incorrect Password" });
        }

        // token isme bhi generate hoga , jaise hi new user login hoga
        
        const token = await genToken(user._id); // user._id is the unique id of the user which is generated by mongodb

        // cookie is a object with has many things
        const isProduction = process.env.NODE_ENV === "production";
        res.cookie("token", token, { // name of cookie is : token
            httpOnly: true,
            maxAge: 10 * 24 * 60 * 60 * 1000, // 10 days (milliseconds)
            sameSite: isProduction ? "None" : "Lax",
            secure: isProduction
        });

        return res.status(200).json(user); // 200 isliye likha hai because ya pe kuch create nhi ho rha h

    } catch(error) {
        console.error("Error occurred during login:", error);
        return res.status(500).json({ message: "Internal server error" });
    }
};

// logout tab hoga jab jo token cookie se hat jayega

export const logOut = async (req, res) => {
    try {
        res.clearCookie("token"); // cookie ko clear kar do (token : name of the cookie)
        return res.status(200).json({ message: "Logged out successfully" });
    } catch (error) {
        console.error("Error occurred during logout:", error);
        return res.status(500).json({ message: "Logout error" });
    }
};

